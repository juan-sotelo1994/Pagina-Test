-- ------------------------------------------------------------ Recuperación de contraseña

-- Códigos de 6 dígitos para renovar la contraseña. Solo se guarda el código cifrado
-- (HMAC-SHA256), nunca el código en sí. Vence a los 2 minutos y sirve una sola vez.
CREATE TABLE IF NOT EXISTS recuperacion_clave (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   integer      NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    codigo_hash  char(64)     NOT NULL,
    creado       timestamptz  NOT NULL DEFAULT now(),
    vence        timestamptz  NOT NULL DEFAULT now() + interval '2 minutes',
    usado        timestamptz,                      -- cuándo se usó o se invalidó
    intentos     smallint     NOT NULL DEFAULT 0,  -- códigos equivocados escritos
    ip           varchar(45)  NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS recuperacion_usuario ON recuperacion_clave (usuario_id, creado DESC);

-- Registra un código nuevo para el correo. Devuelve:
--   'enviar'       se guardó; el panel debe enviar el código por correo
--   'sin_usuario'  el correo no es de un usuario activo (el panel no lo dice, para no revelarlo)
--   'espera'       ya se pidió uno hace menos de 30 segundos
CREATE OR REPLACE FUNCTION solicitar_recuperacion(p_correo text, p_codigo_hash text, p_ip text DEFAULT '')
RETURNS text LANGUAGE plpgsql AS $$
DECLARE
    v_usuario integer;
BEGIN
    SELECT id INTO v_usuario FROM usuarios WHERE correo = lower(trim(p_correo)) AND activo;
    IF v_usuario IS NULL THEN
        RETURN 'sin_usuario';
    END IF;
    IF EXISTS (SELECT 1 FROM recuperacion_clave
               WHERE usuario_id = v_usuario AND creado > now() - interval '30 seconds') THEN
        RETURN 'espera';
    END IF;
    -- Un código nuevo anula los anteriores; los de hace más de un día se borran
    UPDATE recuperacion_clave SET usado = now() WHERE usuario_id = v_usuario AND usado IS NULL;
    DELETE FROM recuperacion_clave WHERE creado < now() - interval '1 day';
    INSERT INTO recuperacion_clave (usuario_id, codigo_hash, ip)
    VALUES (v_usuario, p_codigo_hash, left(coalesce(p_ip, ''), 45));
    RETURN 'enviar';
END
$$;

-- Revisa el código. Devuelve el id del usuario si es correcto y está vigente (y lo marca
-- como usado); si no, NULL. Al quinto código equivocado, el código queda anulado.
CREATE OR REPLACE FUNCTION validar_recuperacion(p_correo text, p_codigo_hash text)
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE
    v_token recuperacion_clave%ROWTYPE;
BEGIN
    SELECT t.* INTO v_token
    FROM recuperacion_clave t
    JOIN usuarios u ON u.id = t.usuario_id
    WHERE u.correo = lower(trim(p_correo)) AND u.activo AND t.usado IS NULL AND t.vence > now()
    ORDER BY t.creado DESC
    LIMIT 1
    FOR UPDATE OF t;

    IF NOT FOUND THEN
        RETURN NULL;
    END IF;
    IF v_token.codigo_hash = p_codigo_hash THEN
        UPDATE recuperacion_clave SET usado = now() WHERE id = v_token.id;
        RETURN v_token.usuario_id;
    END IF;
    UPDATE recuperacion_clave
    SET intentos = intentos + 1,
        usado = CASE WHEN intentos + 1 >= 5 THEN now() END
    WHERE id = v_token.id;
    RETURN NULL;
END
$$;

-- ------------------------------------------------------------ Inventario

CREATE TABLE IF NOT EXISTS proveedores (
    id                varchar(32)  PRIMARY KEY DEFAULT nuevo_id(),
    nombre            varchar(120) NOT NULL,
    nit               varchar(20)  NOT NULL UNIQUE,
    tipo              varchar(40)  NOT NULL,
    contacto          varchar(120) NOT NULL DEFAULT '',
    cargo             varchar(120) NOT NULL DEFAULT '',
    correo            varchar(120) NOT NULL DEFAULT '',
    telefono          varchar(20)  NOT NULL DEFAULT '',
    ciudad            varchar(120) NOT NULL DEFAULT '',
    direccion         varchar(160) NOT NULL DEFAULT '',
    sitio_web         varchar(200) NOT NULL DEFAULT '',
    suministra        text[]       NOT NULL DEFAULT '{}',
    condiciones_pago  varchar(40)  NOT NULL DEFAULT '',
    tiempo_entrega    varchar(120) NOT NULL DEFAULT '',
    notas             varchar(1000) NOT NULL DEFAULT '',
    activo            boolean      NOT NULL DEFAULT true,
    creado            timestamptz  NOT NULL DEFAULT now(),
    creado_por        varchar(120) NOT NULL DEFAULT '',
    actualizado       timestamptz,
    actualizado_por   varchar(120)
);

CREATE TABLE IF NOT EXISTS productos (
    id               varchar(32)   PRIMARY KEY DEFAULT nuevo_id(),
    codigo           varchar(30)   NOT NULL UNIQUE,
    nombre           varchar(120)  NOT NULL,
    categoria        varchar(60)   NOT NULL,
    marca            varchar(120)  NOT NULL DEFAULT '',
    unidad           varchar(30)   NOT NULL DEFAULT 'Unidad',
    descripcion      varchar(1000) NOT NULL DEFAULT '',
    proveedor_id     varchar(32)   REFERENCES proveedores (id) ON DELETE SET NULL,
    costo            numeric(14,2) NOT NULL DEFAULT 0 CHECK (costo >= 0),     -- precio de compra
    precio           numeric(14,2) NOT NULL CHECK (precio >= 0),              -- precio de venta
    iva              smallint      NOT NULL DEFAULT 19 CHECK (iva IN (0, 5, 19)),
    stock            numeric(12,2) NOT NULL DEFAULT 0,
    stock_minimo     numeric(12,2) NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    activo           boolean       NOT NULL DEFAULT true,
    creado           timestamptz   NOT NULL DEFAULT now(),
    creado_por       varchar(120)  NOT NULL DEFAULT '',
    actualizado      timestamptz,
    actualizado_por  varchar(120)
);
CREATE INDEX IF NOT EXISTS productos_proveedor ON productos (proveedor_id);

-- Tres precios de venta para negociar: precio (lista), precio2 (preferencial) y precio3 (mínimo).
-- 0 = no definido (se usa el nivel anterior)
ALTER TABLE productos ADD COLUMN IF NOT EXISTS precio2 numeric(14,2) NOT NULL DEFAULT 0 CHECK (precio2 >= 0);
ALTER TABLE productos ADD COLUMN IF NOT EXISTS precio3 numeric(14,2) NOT NULL DEFAULT 0 CHECK (precio3 >= 0);

CREATE TABLE IF NOT EXISTS servicios (
    id               varchar(32)   PRIMARY KEY DEFAULT nuevo_id(),
    codigo           varchar(30)   NOT NULL UNIQUE,
    nombre           varchar(120)  NOT NULL,
    categoria        varchar(60)   NOT NULL,
    unidad           varchar(30)   NOT NULL DEFAULT 'Servicio',
    descripcion      varchar(1000) NOT NULL DEFAULT '',
    precio           numeric(14,2) NOT NULL CHECK (precio >= 0),
    iva              smallint      NOT NULL DEFAULT 19 CHECK (iva IN (0, 5, 19)),
    activo           boolean       NOT NULL DEFAULT true,
    creado           timestamptz   NOT NULL DEFAULT now(),
    creado_por       varchar(120)  NOT NULL DEFAULT '',
    actualizado      timestamptz,
    actualizado_por  varchar(120)
);

-- Cada equipo de renta es una unidad (con su serial), porque puede estar con un cliente distinto
CREATE TABLE IF NOT EXISTS productos_renta (
    id               varchar(32)   PRIMARY KEY DEFAULT nuevo_id(),
    codigo           varchar(30)   NOT NULL UNIQUE,
    nombre           varchar(120)  NOT NULL,
    categoria        varchar(60)   NOT NULL,
    marca            varchar(120)  NOT NULL DEFAULT '',
    serial           varchar(60)   NOT NULL DEFAULT '',
    descripcion      varchar(1000) NOT NULL DEFAULT '',
    proveedor_id     varchar(32)   REFERENCES proveedores (id) ON DELETE SET NULL,
    unidad           varchar(10)   NOT NULL DEFAULT 'Mes' CHECK (unidad IN ('Mes', 'Semana', 'Día')),
    precio           numeric(14,2) NOT NULL CHECK (precio >= 0),              -- valor de la renta
    iva              smallint      NOT NULL DEFAULT 19 CHECK (iva IN (0, 5, 19)),
    costo            numeric(14,2) NOT NULL DEFAULT 0 CHECK (costo >= 0),     -- precio de compra
    estado           varchar(20)   NOT NULL DEFAULT 'Disponible'
                     CHECK (estado IN ('Disponible', 'Rentado', 'En mantenimiento', 'De baja')),
    cliente_id       varchar(32),
    renta_inicio     date,
    renta_fin        date,
    activo           boolean       NOT NULL DEFAULT true,
    creado           timestamptz   NOT NULL DEFAULT now(),
    creado_por       varchar(120)  NOT NULL DEFAULT '',
    actualizado      timestamptz,
    actualizado_por  varchar(120),
    -- Un equipo rentado siempre tiene cliente y fecha de inicio; el fin no puede ser antes del inicio
    CONSTRAINT renta_con_cliente CHECK (estado <> 'Rentado' OR (cliente_id IS NOT NULL AND renta_inicio IS NOT NULL)),
    CONSTRAINT renta_fechas CHECK (renta_fin IS NULL OR renta_inicio IS NULL OR renta_fin >= renta_inicio)
);
CREATE UNIQUE INDEX IF NOT EXISTS productos_renta_serial_unico ON productos_renta (upper(serial)) WHERE serial <> '';
CREATE INDEX IF NOT EXISTS productos_renta_cliente ON productos_renta (cliente_id) WHERE cliente_id IS NOT NULL;

-- Kárdex: cada entrada, salida o ajuste de stock de un producto
CREATE TABLE IF NOT EXISTS movimientos_inventario (
    id                varchar(32)   PRIMARY KEY DEFAULT nuevo_id(),
    fecha             timestamptz   NOT NULL DEFAULT now(),
    producto_id       varchar(32)   REFERENCES productos (id) ON DELETE SET NULL,
    codigo            varchar(30)   NOT NULL DEFAULT '',   -- se guardan por si luego borran el producto
    nombre            varchar(120)  NOT NULL DEFAULT '',
    cantidad          numeric(12,2) NOT NULL CHECK (cantidad <> 0),   -- positiva = entrada, negativa = salida
    stock_resultante  numeric(12,2) NOT NULL,
    motivo            varchar(200)  NOT NULL,
    referencia        varchar(60)   NOT NULL DEFAULT '',   -- orden de compra o factura del proveedor
    usuario           varchar(120)  NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS movimientos_producto_fecha ON movimientos_inventario (producto_id, fecha DESC);

-- ------------------------------------------------------------ Órdenes de compra

CREATE TABLE IF NOT EXISTS ordenes_compra (
    id                  varchar(32)   PRIMARY KEY DEFAULT nuevo_id(),
    numero              varchar(20)   NOT NULL UNIQUE,              -- ORD-2026-0001
    fecha               date          NOT NULL DEFAULT current_date,
    cotizacion_id       varchar(32)   NOT NULL,
    cotizacion_numero   varchar(20)   NOT NULL,
    cliente_id          varchar(32),                                -- vacío si era un prospecto
    cliente_nombre      varchar(120)  NOT NULL,
    cliente_documento   varchar(40)   NOT NULL DEFAULT '',
    contacto            varchar(120)  NOT NULL DEFAULT '',
    contacto_correo     varchar(120)  NOT NULL DEFAULT '',
    contacto_telefono   varchar(40)   NOT NULL DEFAULT '',
    asunto              varchar(160)  NOT NULL,
    forma_pago          varchar(120)  NOT NULL DEFAULT '',
    tiempo_entrega      varchar(160)  NOT NULL DEFAULT '',
    garantia            varchar(200)  NOT NULL DEFAULT '',
    estado              varchar(12)   NOT NULL DEFAULT 'abierta' CHECK (estado IN ('abierta', 'completada', 'anulada')),
    subtotal            numeric(14,2) NOT NULL DEFAULT 0,             -- antes de descuentos
    descuento           numeric(14,2) NOT NULL DEFAULT 0,
    base                numeric(14,2) NOT NULL DEFAULT 0,
    iva                 numeric(14,2) NOT NULL DEFAULT 0,
    total               numeric(14,2) NOT NULL DEFAULT 0,
    creado              timestamptz   NOT NULL DEFAULT now(),
    creado_por          varchar(120)  NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS ordenes_cliente ON ordenes_compra (cliente_id);
CREATE INDEX IF NOT EXISTS ordenes_fecha ON ordenes_compra (fecha DESC);
-- Una cotización solo puede tener una orden vigente
CREATE UNIQUE INDEX IF NOT EXISTS ordenes_una_por_cotizacion ON ordenes_compra (cotizacion_id) WHERE estado <> 'anulada';

CREATE TABLE IF NOT EXISTS orden_items (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id      varchar(32)   NOT NULL REFERENCES ordenes_compra (id) ON DELETE CASCADE,
    linea         smallint      NOT NULL,
    tipo          varchar(10)   NOT NULL CHECK (tipo IN ('producto', 'servicio', 'renta', 'libre')),
    ref_id        varchar(32)   NOT NULL DEFAULT '',     -- producto, servicio o equipo de renta
    codigo        varchar(30)   NOT NULL DEFAULT '',
    nombre        varchar(160)  NOT NULL,
    detalle       varchar(1000) NOT NULL DEFAULT '',
    unidad        varchar(30)   NOT NULL DEFAULT 'Unidad',
    cantidad      numeric(12,2) NOT NULL CHECK (cantidad > 0),
    precio        numeric(14,2) NOT NULL CHECK (precio >= 0),
    descuento_pct numeric(5,2)  NOT NULL DEFAULT 0 CHECK (descuento_pct BETWEEN 0 AND 100),
    iva_pct       smallint      NOT NULL DEFAULT 19 CHECK (iva_pct IN (0, 5, 19)),
    base          numeric(14,2) NOT NULL,
    valor_iva     numeric(14,2) NOT NULL,
    total         numeric(14,2) NOT NULL,
    UNIQUE (orden_id, linea)
);

-- Servicios vendidos (configuración, asesoría…) que hay que prestar
CREATE TABLE IF NOT EXISTS orden_servicios (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id       varchar(32)   NOT NULL REFERENCES ordenes_compra (id) ON DELETE CASCADE,
    linea          smallint      NOT NULL,
    nombre         varchar(160)  NOT NULL,
    detalle        varchar(1000) NOT NULL DEFAULT '',
    cantidad       numeric(12,2) NOT NULL,
    unidad         varchar(30)   NOT NULL DEFAULT 'Servicio',
    estado         varchar(10)   NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'realizado')),
    realizado      timestamptz,
    realizado_por  varchar(120),
    UNIQUE (orden_id, linea)
);

-- Productos descontados del stock y equipos rentados por cada orden (para poder anularla)
CREATE TABLE IF NOT EXISTS orden_inventario (
    orden_id     varchar(32)   NOT NULL REFERENCES ordenes_compra (id) ON DELETE CASCADE,
    tipo         varchar(10)   NOT NULL CHECK (tipo IN ('producto', 'renta')),
    ref_id       varchar(32)   NOT NULL,
    cantidad     numeric(12,2) NOT NULL DEFAULT 1,
    PRIMARY KEY (orden_id, tipo, ref_id)
);

-- ------------------------------------------------------------ Facturas

CREATE TABLE IF NOT EXISTS facturas (
    id                  varchar(32)   PRIMARY KEY DEFAULT nuevo_id(),
    numero              varchar(20)   NOT NULL UNIQUE,              -- FV-0001
    fecha               date          NOT NULL DEFAULT current_date,
    vence               date          NOT NULL,
    orden_id            varchar(32)   NOT NULL REFERENCES ordenes_compra (id),
    orden_numero        varchar(20)   NOT NULL,
    cotizacion_numero   varchar(20)   NOT NULL DEFAULT '',
    cliente_id          varchar(32),
    cliente_nombre      varchar(120)  NOT NULL,
    cliente_documento   varchar(40)   NOT NULL DEFAULT '',
    contacto            varchar(120)  NOT NULL DEFAULT '',
    contacto_correo     varchar(120)  NOT NULL DEFAULT '',
    contacto_telefono   varchar(40)   NOT NULL DEFAULT '',
    asunto              varchar(160)  NOT NULL DEFAULT '',
    forma_pago          varchar(120)  NOT NULL DEFAULT '',
    estado              varchar(10)   NOT NULL DEFAULT 'Pendiente' CHECK (estado IN ('Pendiente', 'Pagada', 'Anulada')),
    subtotal            numeric(14,2) NOT NULL DEFAULT 0,
    descuento           numeric(14,2) NOT NULL DEFAULT 0,
    base                numeric(14,2) NOT NULL DEFAULT 0,
    iva                 numeric(14,2) NOT NULL DEFAULT 0,
    total               numeric(14,2) NOT NULL DEFAULT 0,
    pago_fecha          date,
    pago_medio          varchar(20),
    pago_referencia     varchar(80),
    pago_usuario        varchar(120),
    creado              timestamptz   NOT NULL DEFAULT now(),
    creado_por          varchar(120)  NOT NULL DEFAULT '',
    CONSTRAINT facturas_vence CHECK (vence >= fecha),
    CONSTRAINT facturas_pago CHECK (estado <> 'Pagada' OR (pago_fecha IS NOT NULL AND pago_medio IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS facturas_cliente ON facturas (cliente_id);
CREATE INDEX IF NOT EXISTS facturas_estado_vence ON facturas (estado, vence);

