-- ------------------------------------------------------------ Vistas

-- Inventario con el valor de cada producto y si hay que reponerlo
CREATE OR REPLACE VIEW vista_inventario AS
SELECT p.id, p.codigo, p.nombre, p.categoria, p.marca, pr.nombre AS proveedor,
       p.stock, p.stock_minimo, p.costo, p.precio,
       (p.stock * p.costo)::numeric(16,2)  AS valor_compra,
       (p.stock * p.precio)::numeric(16,2) AS valor_venta,
       (p.stock_minimo > 0 AND p.stock <= p.stock_minimo) AS por_reponer
FROM productos p
LEFT JOIN proveedores pr ON pr.id = p.proveedor_id
WHERE p.activo;

-- Facturas con su estado del día (las pendientes que pasaron su fecha salen como Vencida)
CREATE OR REPLACE VIEW vista_facturas AS
SELECT f.*, CASE WHEN f.estado = 'Pendiente' AND f.vence < current_date THEN 'Vencida' ELSE f.estado END AS estado_actual
FROM facturas f;
