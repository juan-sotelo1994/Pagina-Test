-- Base de datos del panel de Test-Lab (PostgreSQL 18)
-- Tablas: usuarios, inventario (proveedores, productos, servicios, productos en renta,
-- movimientos), órdenes de compra y facturas.
--
-- Se puede ejecutar varias veces: solo crea lo que no existe.
-- Los id de texto son los mismos que usa hoy el panel (12 caracteres hexadecimales).

CREATE OR REPLACE FUNCTION nuevo_id() RETURNS varchar AS $$
    SELECT substr(replace(gen_random_uuid()::text, '-', ''), 1, 12)
$$ LANGUAGE sql VOLATILE;

-- ------------------------------------------------------------ Usuarios

CREATE TABLE IF NOT EXISTS usuarios (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres       varchar(60)  NOT NULL,
    apellidos     varchar(60)  NOT NULL DEFAULT '',
    correo        varchar(120) NOT NULL,
    rol           varchar(20)  NOT NULL
                  CHECK (rol IN ('superadmin', 'admin', 'vendedor', 'preventa', 'tecnico', 'auxiliar')),
    hash          varchar(255) NOT NULL,              -- contraseña cifrada (werkzeug), nunca en texto plano
    activo        boolean      NOT NULL DEFAULT true,
    creado        timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT usuarios_correo_minusculas CHECK (correo = lower(correo))
);
CREATE UNIQUE INDEX IF NOT EXISTS usuarios_correo_unico ON usuarios (correo);

-- Celular para recibir el código de recuperación por SMS o WhatsApp (formato internacional: +573001234567)
